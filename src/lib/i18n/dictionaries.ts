// Central i18n dictionary. Add a new locale by adding a key to `dictionaries`
// and a matching entry in `locales` — no other code needs to change.
// Arabic/French are intentionally not implemented yet ("coming soon" in the
// language picker) but the shape below makes adding them mechanical.

export const locales = ["he", "en"] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = "he";
export const rtlLocales: Locale[] = ["he"];

export function dirForLocale(locale: string): "rtl" | "ltr" {
  return rtlLocales.includes(locale as Locale) ? "rtl" : "ltr";
}

